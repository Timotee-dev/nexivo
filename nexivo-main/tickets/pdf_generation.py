"""
PDF ticket generation using ReportLab. Each ticket PDF embeds the QR image
already generated by tickets.qr, plus event/holder details, styled to
match the platform's black/luxury aesthetic.
"""

import io

from django.core.files.base import ContentFile
from reportlab.lib import colors
from reportlab.lib.pagesizes import A6
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas


GOLD = colors.HexColor("#d4af37")
BLACK = colors.HexColor("#0a0a0a")
DARK_GRAY = colors.HexColor("#1c1c1c")
WHITE = colors.white
LIGHT_GRAY = colors.HexColor("#9a9a9a")


def generate_ticket_pdf(ticket) -> ContentFile:
    buffer = io.BytesIO()
    width, height = A6
    c = canvas.Canvas(buffer, pagesize=A6)

    c.setFillColor(BLACK)
    c.rect(0, 0, width, height, fill=1, stroke=0)

    c.setFillColor(GOLD)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(10 * mm, height - 15 * mm, "NEXIVO")

    c.setFillColor(WHITE)
    c.setFont("Helvetica-Bold", 13)
    event_title = ticket.event.title
    if len(event_title) > 32:
        event_title = event_title[:30] + "…"
    c.drawString(10 * mm, height - 28 * mm, event_title)

    c.setFillColor(LIGHT_GRAY)
    c.setFont("Helvetica", 9)
    c.drawString(10 * mm, height - 35 * mm, ticket.event.start_datetime.strftime("%a, %d %b %Y · %I:%M %p"))

    if ticket.event.is_physical:
        venue_line = f"{ticket.event.venue_name}, {ticket.event.city}"
    else:
        venue_line = f"Virtual — {ticket.event.virtual_platform}"
    c.drawString(10 * mm, height - 41 * mm, venue_line[:50])

    c.setStrokeColor(DARK_GRAY)
    c.line(10 * mm, height - 46 * mm, width - 10 * mm, height - 46 * mm)

    c.setFillColor(WHITE)
    c.setFont("Helvetica-Bold", 11)
    c.drawString(10 * mm, height - 54 * mm, ticket.holder_name)
    c.setFillColor(GOLD)
    c.setFont("Helvetica", 9)
    c.drawString(10 * mm, height - 60 * mm, ticket.ticket_type.name)

    if ticket.qr_image:
        try:
            ticket.qr_image.open("rb")
            from reportlab.lib.utils import ImageReader
            qr_reader = ImageReader(ticket.qr_image)
            qr_size = 38 * mm
            c.drawImage(
                qr_reader, width - qr_size - 10 * mm, 10 * mm, width=qr_size, height=qr_size,
                preserveAspectRatio=True, mask="auto",
            )
        finally:
            ticket.qr_image.close()

    c.setFillColor(LIGHT_GRAY)
    c.setFont("Helvetica", 7)
    c.drawString(10 * mm, 10 * mm, f"Ticket: {ticket.ticket_code}")
    c.drawString(10 * mm, 6 * mm, "Each QR code is valid for one entry only.")

    c.showPage()
    c.save()
    buffer.seek(0)
    return ContentFile(buffer.read(), name=f"ticket_{ticket.ticket_code}.pdf")


def attach_pdf_to_ticket(ticket):
    pdf_file = generate_ticket_pdf(ticket)
    ticket.pdf_file.save(pdf_file.name, pdf_file, save=True)
    return ticket
